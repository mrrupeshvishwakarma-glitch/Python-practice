# Take age and check if age >= 18 and age <= 25.
age = int(input("Enter your age : = "))
if age >= 18 and age <= 25: 
    print("Age is between 18 and 25")
else:
    print("Age is not between 18 and 25")

# Take temperature and check safe range (20-30).
temperature = int(input("Enter the temperature: = "))
if temperature >= 20 and temperature <= 30:
    print("Temperature is in a safe range")
else:
    print("Temperature is not in a safe range")
