# Take marks and check if marks > 50.
marks = int(input("Enter your marks : = "))
if marks > 50:
    print("Marks are greater than 50")
else:
    print("Marks are not greater than 50")

# Take number and compare with 500.
num = int(input("Enter the number: "))
if num > 500:
    print("The number is greater than 500")
elif num < 500:
    print("The number is less than 500")
else:
    print("The number is equal to 500")
